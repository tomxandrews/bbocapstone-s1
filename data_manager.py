def get_dataset(function_id: int, include_weekly: bool = True, up_to_week: int = 2) -> Tuple[np.ndarray, np.ndarray]:
    """
    Retrieves the input coordinates X and outputs y for a specific function.

    Parameters:
    -----------
    function_id : int (1 through 8)
    include_weekly : bool
        If True, appends weekly query-output observations to starter data.
    up_to_week : int
        Maximum weekly cycle to include (e.g., 2 includes Week 1 and Week 2).

    Returns:
    --------
    X : np.ndarray of shape (N, dim)
    y : np.ndarray of shape (N,)
    """
    if function_id not in RAW_STARTER_DATA:
        raise ValueError(f"Invalid function_id: {function_id}. Must be between 1 and 8.")

    raw = RAW_STARTER_DATA[function_id]
    X = raw['X'].copy()
    y = raw['y'].copy()

    if include_weekly:
        for week_num in range(1, up_to_week + 1):
            week_key = f"Week {week_num}"
            if week_key in HISTORICAL_FEEDBACK and function_id in HISTORICAL_FEEDBACK[week_key]:
                entry = HISTORICAL_FEEDBACK[week_key][function_id]
                if entry['y'] is not None:
                    X = np.vstack([X, entry['x']])
                    y = np.append(y, entry['y'])

    return X, y


def get_current_best(function_id: int, up_to_week: int = 2) -> Tuple[np.ndarray, float]:
    """
    Returns the coordinates and scalar value of the all-time maximum observed output.
    """
    X, y = get_dataset(function_id, include_weekly=True, up_to_week=up_to_week)
    best_idx = int(np.argmax(y))
    return X[best_idx].copy(), float(y[best_idx])


def get_metadata(function_id: int) -> Dict[str, Any]:
    """
    Returns descriptive metadata for a function.
    """
    if function_id not in RAW_STARTER_DATA:
        raise ValueError(f"Invalid function_id: {function_id}. Must be between 1 and 8.")
    
    raw = RAW_STARTER_DATA[function_id]
    return {
        'function_id': function_id,
        'dim': raw['dim'],
        'domain': raw['domain'],
        'description': raw['description'],
        'n_starter': len(raw['y'])
    }


def format_coordinate_string(x_vector: np.ndarray) -> str:
    """
    Converts a continuous NumPy coordinate vector into the exact portal submission string:
    6 decimal places per dimension, joined by hyphens, with no spaces.
    Example: [0.66011412, 0.6740263] -> '0.660114-0.674026'
    """
    return "-".join(f"{float(val):.6f}" for val in x_vector)


def parse_coordinate_string(coord_str: str) -> np.ndarray:
    """
    Parses a portal submission string back into a continuous NumPy vector.
    """
    return np.array([float(token.strip()) for token in coord_str.split("-")])


def get_residual_benchmark_df() -> pd.DataFrame:
    """
    Constructs a DataFrame summarizing historical prediction residuals:
    e = |y_actual - mu| across completed iteration cycles.
    """
    rows = []
    for week_key in ['Week 1', 'Week 2']:
        for fid in range(1, 9):
            entry = HISTORICAL_FEEDBACK[week_key][fid]
            actual = entry['y']
            pred = entry['pred_mu']
            res = abs(actual - pred) if actual is not None and pred is not None else np.nan
            rows.append({
                'Cycle': week_key,
                'Function': f"Function {fid}",
                'Dim': RAW_STARTER_DATA[fid]['dim'],
                'Actual Output (y)': actual,
                'Predicted Mean (mu)': pred,
                'Residual Error (e)': res
            })
    return pd.DataFrame(rows)


def export_summary_dataframe(up_to_week: int = 2) -> pd.DataFrame:
    """
    Generates a master summary table tracking baseline through current all-time bests.
    """
    summary = []
    for fid in range(1, 9):
        meta = get_metadata(fid)
        X_init, y_init = get_dataset(fid, include_weekly=False)
        X_cum, y_cum = get_dataset(fid, include_weekly=True, up_to_week=up_to_week)
        best_x, best_y = get_current_best(fid, up_to_week=up_to_week)
        
        summary.append({
            'Function': f"Function {fid}",
            'Dim': meta['dim'],
            'Domain Scenario': meta['domain'],
            'N Starter': len(y_init),
            'N Total': len(y_cum),
            'Initial Best y': float(np.max(y_init)),
            'Current Best y': best_y,
            'Current Best Vector': format_coordinate_string(best_x)
        })
    return pd.DataFrame(summary)


